package com.pansauce.model;

public class Ingredient {
    private String gti;
    private String name;

    public String getGti() {
        return gti;
    }

    public String getName() {
        return name;
    }

    public void setGti(String gti) {
        this.gti = gti;
    }

    public void setName(String name) {
        this.name = name;
    }
}
